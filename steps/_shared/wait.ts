import type { StepContext, WaitEvent } from '../../packages/step-kit/src/index.ts';

/**
 * Сроки ожидания внешних событий шагами сборки, деплоя и теста на стенде: после срока наблюдатель
 * роняет шаг с ошибкой, которую шаг кладет в событие ожидания.
 */
export const WAIT_MS = {
  /** Пока Bamboo заведет ветку плана после пуша. */
  planBranch: 10 * 60_000,
  /** Сборку коммита, включая очередь. */
  build: 45 * 60_000,
  /** Деплой; на этапе 0 деплои шли от 3 до 20 минут. */
  deploy: 40 * 60_000,
  /** Деплой, который владелец запускает в Bamboo сам. */
  manualDeploy: 60 * 60_000,
  /** Новый под с образом сборки и ответ стенда после деплоя. */
  rollout: 10 * 60_000,
  /** Деплой связанных прогонов задачи перед тестом на стенде. */
  linked: 2 * 60 * 60_000,
};

/** Срок в минутах для текста ошибки. */
export function minutes(ms: number): number {
  return Math.round(ms / 60_000);
}

/**
 * С какого времени шаг ждет событие одного из видов kinds: если он ждал его перед этим входом, - прежнее время, иначе
 * сейчас. Так повторная проверка и "проверить сейчас" не сдвигают срок ожидания.
 */
export function sinceOf(c: StepContext, ...kinds: WaitEvent['kind'][]): string {
  const w = c.waited;
  return w && kinds.includes(w.kind) && 'since' in w ? w.since : new Date().toISOString();
}
